#!/usr/bin/env python3
"""Emit the stub-census table that ntdll's #UD probe reads.

    tools/pe/emit-stub-census.py <image.exe> [-o header] [--samples N]

Why this exists. docs/compatibility/forza-horizon-6-ios.md §4q ends with one
question that a log has not yet answered: when the game dies on
STATUS_ILLEGAL_INSTRUCTION at image+0x537099c, is that stub the ONLY protected
entry still holding its ciphertext, or are they all still ciphertext? The two
answers point in opposite directions and cannot be told apart from the bytes at
one address:

    all (or most) still ciphertext -> the protector's decrypt pass never ran
                                      (or was defeated); the game dies on the
                                      first protected call it makes
    only this one still ciphertext -> the pass ran and missed this entry, so
                                      the fault is about which call was made

`tools/pe/protected-stubs.py` enumerates the set. This script samples it down to
something small enough to compile into ntdll, and the run-time probe
([stub-census] in wine/dlls/ntdll/exception.c) reports how many samples still
begin with 0xEA at the moment of the fault.

Sampling is uniform over the RVA-sorted list, so it is spread over the whole
set rather than clustered at the image start; the faulting RVA is always added.
This is a diagnostic. It reads and reports; it does not decrypt anything.
"""

import argparse
import subprocess
import sys
import tempfile
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FAULT_RVA = 0x537099C


def stub_rvas(image):
    with tempfile.TemporaryDirectory() as t:
        out = os.path.join(t, "stubs.txt")
        subprocess.run(
            [sys.executable, os.path.join(HERE, "protected-stubs.py"),
             image, "--watch-list", out],
            check=True, stdout=subprocess.DEVNULL,
        )
        with open(out) as f:
            return [int(line, 16) for line in f if line.strip()]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("image")
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("--samples", type=int, default=128)
    a = ap.parse_args()

    rvas = sorted(set(stub_rvas(a.image)))
    if not rvas:
        raise SystemExit("no stubs found -- wrong image?")

    n = min(a.samples, len(rvas))
    # Uniform stride over the sorted set, offset to the middle of each bucket.
    picks = [rvas[(i * len(rvas) + len(rvas) // 2) // n] for i in range(n)]
    if FAULT_RVA not in picks:
        picks.append(FAULT_RVA)
    picks = sorted(set(picks))

    with open(a.output, "w") as f:
        f.write("/* Generated by tools/pe/emit-stub-census.py -- do not edit.\n"
                " * Sampled protected-entry RVAs of %s, read by [stub-census]. */\n"
                % os.path.basename(a.image))
        f.write("#define MADEIRA_STUB_CENSUS_COUNT %du\n" % len(picks))
        f.write("#define MADEIRA_STUB_FAULT_RVA 0x%xull\n" % FAULT_RVA)
        f.write("static const unsigned long long madeira_stub_census_rva[] = {\n")
        for i in range(0, len(picks), 4):
            f.write("    " + ", ".join("0x%xull" % r for r in picks[i:i + 4]) + ",\n")
        f.write("};\n")

    print("wrote %d sampled RVAs of %d stubs to %s" % (len(picks), len(rvas), a.output))


if __name__ == "__main__":
    main()
